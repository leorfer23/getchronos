test("apiErrorClass: the CLI's error code first, then the words", () => {
  assert.equal(apiErrorClass("authentication_failed", "Failed to authenticate"), "auth");
  assert.equal(apiErrorClass("server_error", "Login expired · Please run /login"), "auth");
  assert.equal(apiErrorClass("rate_limit", "x"), "rate_limit");
  assert.equal(apiErrorClass("server_error", "You've hit your session limit · resets 5pm"), "rate_limit");
  assert.equal(apiErrorClass("server_error", "API Error: Your computer went to sleep mid-response."), "network");
  assert.equal(apiErrorClass("server_error", "API Error: Connection lost mid-response."), "network");
  assert.equal(apiErrorClass("server_error", "API Error: 529 Overloaded"), "overloaded");
  assert.equal(apiErrorClass("server_error", "API Error: 500 internal"), "other");
});

test("clauses: the pieces an ask repeats in — a long brief gives its head and tail, code and logs give nothing", () => {
  assert.deepEqual(clauses("Fix the login redirect. And DM me when done!"), ["Fix the login redirect", "DM me when done"]);
  assert.deepEqual(clauses("fix the login redirect and dm me when done"), ["fix the login redirect", "dm me when done"], "a standing request at the end of a goal is its own clause");
  assert.deepEqual(clauses("ok"), [], "one word is not an ask");
  assert.deepEqual(clauses("const x = a[0] + b{1} / (c * d);"), []);
  const brief = "Build the export. " + "Lorem ipsum dolor sit amet. ".repeat(80) + "Put it in Downloads.";
  const c = clauses(brief);
  assert.equal(c[0], "Build the export");
  assert.equal(c[c.length - 1], "Put it in Downloads");
});

test("isCorrection / isRequest: corrections count once, standing requests once they repeat", () => {
  for (const s of ["no, the other table", "never push to main", "always put it in downloads", "less text, more concise", "don't ask him, read it yourself", "next time check the logs first", "nunca hagas merge sin preguntar"])
    assert.equal(isCorrection(s), true, s);
  for (const s of ["fix the login redirect", "what is the status", "looks good"]) assert.equal(isCorrection(s), false, s);
  for (const s of ["dm me when done", "put it in downloads", "let me know when it ships", "avisame cuando termines"]) assert.equal(isRequest(s), true, s);
  assert.equal(isRequest("fix the login redirect"), false);
});

test("clusterSaid groups the same ask said again; repeated = more than once, in more than one terminal", () => {
  const said = [
    { text: "and DM me when done", session_id: "s1", at: T0 },
    { text: "dm me when you're done", session_id: "s2", at: T0 + 1 },
    { text: "DM me when done", session_id: "s3", at: T0 + 2 },
    { text: "fix the login redirect", session_id: "s1", at: T0 + 3 },
    { text: "put it in downloads", session_id: "s4", at: T0 + 4 },
    { text: "put it in downloads", session_id: "s4", at: T0 + 5 },
  ];
  const c = clusterSaid(said);
  const dm = c.find((x) => /dm/i.test(x.text))!;
  assert.equal(dm.count, 3);
  assert.equal(dm.sessions, 3);
  assert.equal(dm.text, "DM me when done", "the shortest way he said it");
  assert.equal(dm.request, true);
  assert.equal(repeated(dm), true);
  const dl = c.find((x) => /downloads/.test(x.text))!;
  assert.equal(repeated(dl), false, "twice in one terminal is a conversation, not a repeat");
  const pasted = clusterSaid([
    { text: "connection reset by peer", session_id: "s1", at: T0 },
    { text: "connection reset by peer", session_id: "s1", at: T0 },
    { text: "connection reset by peer", session_id: "s1", at: T0 },
  ]);
  assert.equal(pasted[0].count, 1, "one pasted log repeating a line is one turn");
  assert.ok(clauseSimilarity("put it in downloads", "put them in downloads please") >= 0.5);
});

test("duplicateTerminals: opened in the window while a live terminal of the same workspace had the same goal; a Lead and its worker are not a pair", () => {
  const at = (h: number) => iso(T0 + h * 3600_000);
  const rows = [
    { id: "a", workspace_id: "w1", goal: "fix the login redirect loop", spawn_goal: null, lead_id: null, created_at: at(-2), ended_at: null },
    { id: "b", workspace_id: "w1", goal: "fix the login redirect loop again", spawn_goal: null, lead_id: null, created_at: at(1), ended_at: at(2) },
    { id: "c", workspace_id: "w2", goal: "fix the login redirect loop", spawn_goal: null, lead_id: null, created_at: at(3), ended_at: null },
    { id: "d", workspace_id: "w1", goal: "fix the login redirect loop", spawn_goal: null, lead_id: "a", created_at: at(4), ended_at: null },
    { id: "e", workspace_id: "w1", goal: "write the quarterly report", spawn_goal: null, lead_id: null, created_at: at(5), ended_at: null },
    { id: "f", workspace_id: "w3", goal: "rotate the keys", spawn_goal: null, lead_id: null, created_at: at(6), ended_at: at(7) },
    { id: "g", workspace_id: "w3", goal: "rotate the keys", spawn_goal: null, lead_id: null, created_at: at(8), ended_at: null },
  ] as any[];
  // b duplicates a (same ws, a live). c is another workspace. d is a's own worker. e is other work. g opened after f ended.
  assert.equal(duplicateTerminals(rows, iso(T0), iso(T0 + 86_400_000)), 1);
});
